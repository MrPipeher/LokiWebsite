#!/usr/bin/env node
/**
 * Regenerates the vouch carousel in index.html from assets/reviews.
 *
 * Order: NEWEST FIRST. The timestamp is parsed from the screenshot filename
 * ("Screenshot 2026-11-01 084331.png" -> 2026-11-01 08:43:31). Files without a
 * parseable timestamp fall back to their last-modified time.
 *
 * Usage:  node tools/sync-reviews.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const siteDir = path.resolve(toolsDir, '..');
const reviewsDir = path.join(siteDir, 'assets', 'reviews');
const htmlPath = path.join(siteDir, 'index.html');

const START = '<!-- VOUCH-SLIDES:START | generated by tools/sync-reviews.mjs (newest first) -->';
const END = '<!-- VOUCH-SLIDES:END -->';
const IMAGE_RE = /\.(png|jpe?g|webp|avif|gif)$/i;
const STAMP_RE = /(\d{4})-(\d{2})-(\d{2})[ _T-](\d{2})[:\-]?(\d{2})[:\-]?(\d{2})/;
const INDENT = ' '.repeat(12);

if (!fs.existsSync(reviewsDir)) {
  console.error(`Reviews folder not found: ${reviewsDir}`);
  process.exit(1);
}
if (!fs.existsSync(htmlPath)) {
  console.error(`index.html not found: ${htmlPath}`);
  process.exit(1);
}

function timestampOf(fileName) {
  const match = fileName.match(STAMP_RE);
  if (match) {
    const [, y, mo, d, h, mi, s] = match;
    return Number(`${y}${mo}${d}${h}${mi}${s}`);
  }
  const stat = fs.statSync(path.join(reviewsDir, fileName));
  return Math.floor(stat.mtimeMs);
}

const files = fs
  .readdirSync(reviewsDir)
  .filter((name) => IMAGE_RE.test(name))
  .map((name) => ({ name, stamp: timestampOf(name) }))
  .sort((a, b) => (b.stamp - a.stamp) || b.name.localeCompare(a.name, 'en'));

if (!files.length) {
  console.error(`No images found in ${reviewsDir}`);
  process.exit(1);
}

const slides = files.map(({ name }, index) => {
  const src = `assets/reviews/${encodeURIComponent(name)}`;
  const state = index === 0
    ? 'vouch-slide active'
    : 'vouch-slide';
  const loading = index === 0 ? 'eager' : 'lazy';
  return `${INDENT}<img class="${state}" src="${src}" alt="Loki customer review ${index + 1}" loading="${loading}" decoding="async">`;
});

const generated = [`${INDENT}${START}`, ...slides, `${INDENT}${END}`].join('\n');
let html = fs.readFileSync(htmlPath, 'utf8');
const eol = html.includes('\r\n') ? '\r\n' : '\n';

if (html.includes(START) && html.includes(END)) {
  // Consume the leading indentation too, otherwise each run would add another indent level.
  const escapeRe = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = new RegExp(`^[ \\t]*${escapeRe(START)}[\\s\\S]*?^[ \\t]*${escapeRe(END)}`, 'm');
  html = html.replace(pattern, generated);
} else {
  // First run: fill the empty/legacy vouch-track and add the markers.
  const trackPattern = /(<div class="vouch-track" id="vouchTrack">)([\s\S]*?)(<\/div>)/;
  if (!trackPattern.test(html)) {
    console.error('Could not find <div class="vouch-track" id="vouchTrack"> in index.html');
    process.exit(1);
  }
  html = html.replace(trackPattern, `$1\n${generated}\n${' '.repeat(10)}$3`);
}

// Keep the file's existing line-ending style (this repo uses CRLF).
fs.writeFileSync(htmlPath, html.replace(/\r?\n/g, eol), 'utf8');

console.log(`Synced ${files.length} reviews into index.html (newest first).`);
console.log(`  first slide: ${files[0].name}`);
console.log(`  last slide : ${files[files.length - 1].name}`);
